export function menuIcon(kind: string) {
  const silhouette = silhouettes[kind];
  if (!silhouette) return "";
  const [x, y, width, height] = silhouette.bounds;
  const frameHeight = (height * 40) / 34;
  const frameWidth = Math.max(width + 12, frameHeight);
  const frame = `${x - (frameWidth - width) / 2} ${y + height + 10 - frameHeight} ${frameWidth} ${frameHeight}`;
  const clip = `menu-silhouette-${kind}`;
  return `<svg viewBox="${frame}" preserveAspectRatio="xMidYMax meet" aria-hidden="true" focusable="false"><defs><clipPath id="${clip}" clipPathUnits="userSpaceOnUse"><path d="${silhouette.path}"/></clipPath></defs><image href="${import.meta.env.BASE_URL}ui/hud/art/menu-atlas.png" width="1774" height="887" clip-path="url(#${clip})"/></svg>`;
}
